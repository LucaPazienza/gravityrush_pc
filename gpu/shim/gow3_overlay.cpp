void SetOpen(bool value) {
    if (menu_open.exchange(value) == value) {
        return;
    }
    ImGui::GetIO().MouseDrawCursor = value;
    if (value) {
        requested_tab = Gow3Settings::Get().menu_tab;
    }
    if (!value && dirty) {
        dirty = false;
        Gow3Settings::Save();
    }
}

