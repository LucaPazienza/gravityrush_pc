"""Writes src/gr_isa_sites.inc: where Gravity Rush Remastered 01.00 (eboot, libc.prx, libSceFios2.prx)
uses instructions the PS4's Jaguar CPU has but older PC CPUs lack (runtime_newisa.c):
BMI1 (ANDN, BEXTR, BLSI, BLSMSK, BLSR, TZCNT), LZCNT and MOVBE. Intel CPUs before Haswell have none of
them; there ANDN & co. stop with an illegal instruction and LZCNT/TZCNT silently run as BSR/BSF.

Only image offsets, lengths and kinds are written: the runtime decodes each site before it touches it,
so a different build of the game just leaves the sites alone.

Usage (MSYS2 CLANG64, port folder, after a first start so out/eboot.elf and out/link.json exist):
  python scripts/gr_isa_sites.py <game folder>
"""
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

PORT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PORT / 'scripts'))
from prepare import parse_self  # noqa: E402

KINDS = ['andn', 'bextr', 'blsi', 'blsmsk', 'blsr', 'tzcnt', 'lzcnt', 'movbe']


def eboot_headers(elf_bytes):
    import struct
    phoff = struct.unpack_from('<Q', elf_bytes, 0x20)[0]
    phnum = struct.unpack_from('<H', elf_bytes, 0x38)[0]
    keys = ('type', 'flags', 'offset', 'vaddr', 'paddr', 'filesz', 'memsz', 'align')
    return elf_bytes, [dict(zip(keys, struct.unpack_from('<IIQQQQQQ', elf_bytes, phoff + i * 56))) for i in range(phnum)]


def read_encoded(data, pos, encoding, hdr):
    """A DWARF pointer of eh_frame_hdr (pcrel / datarel, 4 or 8 bytes); addresses = segment offsets."""
    import struct
    kind = encoding & 0x0f
    value, size = {0x03: ('<I', 4), 0x04: ('<Q', 8), 0x0b: ('<i', 4), 0x0c: ('<q', 8)}[kind]
    value = struct.unpack_from(value, data, pos)[0]
    if encoding & 0x70 == 0x10:
        value += pos
    elif encoding & 0x70 == 0x30:
        value += hdr
    return value, size


def code_range(code, eh_frame_hdr):
    """(start, end) of the functions listed in eh_frame_hdr: the executable segment also holds
    read-only data and the unwind tables, where bytes may look like these instructions."""
    import struct
    h = eh_frame_hdr
    _, ptr_enc, count_enc, table_enc = code[h:h + 4]
    pos = h + 4
    _, n = read_encoded(code, pos, ptr_enc, h)
    pos += n
    count, n = read_encoded(code, pos, count_enc, h)
    pos += n
    start, end = None, 0
    for _ in range(count):
        _, n = read_encoded(code, pos, table_enc, h)
        pos += n
        fde, n = read_encoded(code, pos, table_enc, h)
        pos += n
        begin = struct.unpack_from('<i', code, fde + 8)[0] + fde + 8
        length = struct.unpack_from('<I', code, fde + 12)[0]
        start = begin if start is None else min(start, begin)
        end = max(end, begin + length)
    return start, end


def executable_code(elf, ph):
    """[(vaddr, code bytes, code start, code end)] of an ELF's executable segments."""
    eh = next(p for p in ph if p['type'] == 0x6474e550)
    for p in ph:
        if p['type'] == 1 and p['flags'] & 1 and p['filesz']:
            code = elf[p['offset']:p['offset'] + p['filesz']]
            assert p['vaddr'] == 0 and eh['vaddr'] < len(code)
            yield (p['vaddr'], code) + code_range(code, eh['vaddr'])


def scan(code, base, work):
    raw = work / 'seg.bin'
    obj = work / 'seg.o'
    raw.write_bytes(code)
    subprocess.run(['llvm-objcopy', '-I', 'binary', '-O', 'elf64-x86-64', '--rename-section',
                    '.data=.text,alloc,load,code', str(raw), str(obj)], check=True)
    out = subprocess.run(['llvm-objdump', '-d', '-M', 'intel', str(obj)], check=True, capture_output=True,
                         text=True).stdout
    line_re = re.compile(r'^\s*([0-9a-f]+):\s+((?:[0-9a-f]{2} )+)\s*(\S+)')
    sites = []
    for line in out.splitlines():
        m = line_re.match(line)
        if not m or m.group(3) not in KINDS:
            continue
        sites.append((base + int(m.group(1), 16), len(m.group(2).split()), KINDS.index(m.group(3))))
    return sites


def main():
    game = Path(sys.argv[1])
    link = json.loads((PORT / 'out' / 'link.json').read_text())
    sites = []
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        images = [(0, eboot_headers((PORT / 'out' / 'eboot.elf').read_bytes()))]
        for module in link['modules']:
            elf, _, ph, _, _ = parse_self((game / 'sce_module' / module['file']).read_bytes())
            images.append((int(module['base'], 16), (elf, ph)))
        for base, (elf, ph) in images:
            for vaddr, code, start, end in executable_code(elf, ph):
                sites += [s for s in scan(code, base + vaddr, work) if base + start <= s[0] < base + end]
    sites.sort()
    out = PORT / 'src' / 'gr_isa_sites.inc'
    lines = ['/* Generated by scripts/gr_isa_sites.py: Gravity Rush Remastered 01.00 image offsets of BMI1, LZCNT and',
             ' * MOVBE instructions (eboot, libc.prx, libSceFios2.prx). {offset, length, kind}; kinds: ' +
             ', '.join(f'{i} {k}' for i, k in enumerate(KINDS)) + '. */']
    lines += [f'{{0x{o:x},{n},{k}}},' for o, n, k in sites]
    out.write_bytes(('\n'.join(lines) + '\n').encode())
    counts = {k: sum(1 for s in sites if s[2] == i) for i, k in enumerate(KINDS)}
    print(f'Wrote {out}: {len(sites)} sites {counts}')


if __name__ == '__main__':
    main()
